def get_image_paths():
    """Get all original image paths (dog.jpg + dataset)."""
    paths = [ORIGINAL_IMAGE_PATH]
    if os.path.isdir(DATASET_DIR):
        for filename in sorted(os.listdir(DATASET_DIR)):
            path = os.path.join(DATASET_DIR, filename)
            if os.path.isfile(path) and filename.lower().endswith(IMAGE_EXTENSIONS):
                paths.append(path)

    seen = set()
    unique = []
    for p in paths:
        rp = os.path.realpath(p)
        if rp not in seen:
            seen.add(rp)
            unique.append(p)
    return unique


def get_adv_path(image_path: str) -> str:
    """Get the adversarial image path for a given original."""
    stem = os.path.splitext(os.path.basename(image_path))[0]
    return os.path.join(ADV_DIR, f"adv_{stem}.png")


def load_llava_results() -> dict:
    """Load LLaVA white-box results for comparison."""
    if os.path.isfile(LLAVA_RESULTS_PATH):
        with open(LLAVA_RESULTS_PATH) as f:
            return json.load(f)
    return {}


def keyword_analysis(desc: str, source_kw: str = SOURCE_KEYWORD,
                     target_kw: str = TARGET_KEYWORD) -> dict:
    """Check for source/target keywords in description."""
    desc_lower = desc.lower()
    return {
        "has_source": source_kw in desc_lower,
        "has_target": target_kw in desc_lower,
    }


def save_json(data, filepath):
    with open(filepath, "w") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)


