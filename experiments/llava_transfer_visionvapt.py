"""
Transfer Attack Evaluation: LLaVA-1.5-7B (white-box) → vision-vapt (black-box API)

Tests whether adversarial perturbations crafted on LLaVA-1.5-7B (white-box)
transfer to the vision-vapt model served via the OAC API (black-box).

Pipeline:
  1. Load adversarial images generated by LLaVA-1.5-7B (epsilon=8/255, 300 iters)
  2. Load corresponding original images
  3. Query vision-vapt API with both clean and adversarial images
  4. Compare descriptions: did "cat" appear? did "dog" disappear?

Perturbation safety:
  - All adversarial images were hard-clamped to epsilon=8/255 during generation
  - L-inf = 0.0314 (max 3.1% per-pixel change), mean_abs ~2.5%
  - Visually imperceptible to human eyes

Output:
  outputs/llava_transfer_visionvapt/
    results/              -- per-image JSON + aggregate JSON
    summary_report.txt    -- text summary

Usage:
    PYTHONPATH=. .venv/bin/python experiments/llava_transfer_visionvapt.py
    PYTHONPATH=. .venv/bin/python experiments/llava_transfer_visionvapt.py --image dog.jpg
"""

