from dotenv import load_dotenv

urllib3.disable_warnings(urllib3.exceptions.InsecureRequestWarning)


# ============================================================
# CONFIGURATION
# ============================================================

load_dotenv()

API_KEY = os.environ.get("OAC_API_KEY", "")
BASE_URL = os.environ.get("OAC_BASE_URL", "https://api.ai.oac")
MODEL_NAME = os.environ.get("OAC_VISION_MODEL", "vision-vapt")

ADV_DIR = "outputs/llava_attack_targeted/adversarial_examples"
LLAVA_RESULTS_PATH = "outputs/llava_attack_targeted/results/aggregate_results.json"
ORIGINAL_IMAGE_PATH = "dog.jpg"
DATASET_DIR = "data/vlm"
IMAGE_EXTENSIONS = (".jpg", ".jpeg", ".png", ".webp")

OUTPUT_DIR = "outputs/llava_transfer_visionvapt"

QUESTION = "What do you see in this image?"
MAX_TOKENS = 200
REQUEST_TIMEOUT = 120
MAX_RETRIES = 3
RETRY_BACKOFF = 5

SOURCE_KEYWORD = "dog"
TARGET_KEYWORD = "cat"


# ============================================================
# API CLIENT
# ============================================================

class VisionVaptClient:
    """Simple client for the vision-vapt API."""

    def __init__(self, base_url: str, api_key: str, model: str):
        self.base_url = base_url.rstrip("/")
        self.api_key = api_key
        self.model = model
        self.headers = {
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        }

    def describe(self, pil_image: Image.Image,
                 question: str = QUESTION,
                 max_tokens: int = MAX_TOKENS) -> str:
        """Send image to API and get description."""
        img_b64 = self._encode_image(pil_image)

        payload = {
            "model": self.model,
            "messages": [
                {"role": "user", "content": [
                    {"type": "text", "text": question},
                    {"type": "image_url",
                     "image_url": {"url": f"data:image/jpeg;base64,{img_b64}"}},
                ]}
            ],
            "max_tokens": max_tokens,
            "temperature": 0.1,
        }

        for attempt in range(MAX_RETRIES):
            try:
                resp = requests.post(
                    f"{self.base_url}/v1/chat/completions",
                    headers=self.headers,
                    json=payload,
                    timeout=REQUEST_TIMEOUT,
                    verify=False,
                )
                if resp.status_code == 200:
                    data = resp.json()
                    content = data["choices"][0]["message"].get("content", "")
                    finish = data["choices"][0].get("finish_reason", "")
                    usage = data.get("usage", {})
                    return content.strip() if content else f"<empty response, finish={finish}>"
                elif resp.status_code == 503:
                    print(f"    [API] 503, retrying in {RETRY_BACKOFF}s... (attempt {attempt+1}/{MAX_RETRIES})")
                    time.sleep(RETRY_BACKOFF)
                    continue
                else:
                    return f"<error {resp.status_code}: {resp.text[:200]}>"
            except Exception as e:
                if attempt == MAX_RETRIES - 1:
                    return f"<error: {e}>"
                print(f"    [API] exception, retrying: {e} (attempt {attempt+1}/{MAX_RETRIES})")
                time.sleep(RETRY_BACKOFF)

        return "<error: max retries exceeded>"

    def _encode_image(self, pil_image: Image.Image) -> str:
        buf = io.BytesIO()
        pil_image.save(buf, format="JPEG", quality=95)
        return base64.b64encode(buf.getvalue()).decode()


