def main():
    parser = argparse.ArgumentParser(
        description="Transfer attack: LLaVA-1.5-7B → vision-vapt API"
    )
    parser.add_argument("--image", type=str, default=None,
                        help="Single image to evaluate")
    parser.add_argument("--output-dir", type=str, default=OUTPUT_DIR,
                        help="Output directory")
    args = parser.parse_args()

    output_dir = args.output_dir
    output_dirs = {
        "base": output_dir,
        "results": os.path.join(output_dir, "results"),
    }
    for d in output_dirs.values():
        os.makedirs(d, exist_ok=True)

    print()
    print("=" * 70)
    print("TRANSFER ATTACK: LLaVA-1.5-7B (white-box) → vision-vapt (black-box)")
    print("=" * 70)

    print()
    print("CONFIGURATION")
    print(f"  White-box model  : LLaVA-1.5-7B (bfloat16, 300 iters)")
    print(f"  Black-box model  : {MODEL_NAME} (API, no gradients)")
    print(f"  API base URL     : {BASE_URL}")
    print(f"  Perturbation     : epsilon=8/255 (L-inf=0.0314, max 3.1%/pixel)")
    print(f"  Source keyword   : {SOURCE_KEYWORD}")
    print(f"  Target keyword   : {TARGET_KEYWORD}")
    print(f"  Question         : {QUESTION}")
    print(f"  Max tokens       : {MAX_TOKENS}")
    print()
    print("OUTPUT")
    print(f"  Base: {output_dirs['base']}")
    print(f"  Results: {output_dirs['results']}")

    # --- Verify API connectivity ---
    print()
    print("-" * 70)
    print("VERIFYING API CONNECTIVITY")
    print("-" * 70)

    client = VisionVaptClient(BASE_URL, API_KEY, MODEL_NAME)
    test_resp = client.describe(Image.new("RGB", (100, 100), "blue"),
                                question="What color is this image?",
                                max_tokens=20)
    if test_resp.startswith("<error") or test_resp.startswith("<empty"):
        print(f"  API test FAILED: {test_resp}")
        return
    print(f"  API test OK: {test_resp}")

    # --- Collect images ---
    if args.image:
        image_paths = [args.image]
    else:
        image_paths = get_image_paths()

    print()
    print(f"  Images to evaluate: {len(image_paths)}")
    for p in image_paths:
        adv_p = get_adv_path(p)
        exists = os.path.isfile(adv_p)
        print(f"    - {p}  adv: {'found' if exists else 'MISSING'}")

    # --- Load LLaVA results ---
    llava_results = load_llava_results()
    if llava_results:
        print()
        print(f"  Loaded LLaVA white-box results: {LLAVA_RESULTS_PATH}")
    else:
        print()
        print(f"  WARNING: LLaVA results not found at {LLAVA_RESULTS_PATH}")

    # --- Run evaluation ---
    results = []
    start_time = time.time()

    for image_path in image_paths:
        try:
            result = evaluate_single_image(
                image_path=image_path,
                client=client,
                llava_results=llava_results,
                output_dirs=output_dirs,
            )
            if result:
                results.append(result)
        except Exception as exc:
            print(f"  ERROR: {exc}")
            import traceback
            traceback.print_exc()

    total_time = time.time() - start_time

    if not results:
        print()
        print("No images were successfully processed.")
        return

    total = len(results)

    # --- Final summary ---
    print()
    print()
    print("=" * 70)
    print("FINAL TRANSFER RESULTS")
    print("=" * 70)

    print()
    print(f"{'Image':<16}"
          f"{'VVP Clean':<12}"
          f"{'VVP Adv':<12}"
          f"{'Changed':<9}"
          f"{'SrcRm':<7}"
          f"{'TgtApp':<8}"
          f"{'FullXfer':<9}")
    print("-" * 70)

    for r in results:
        def short_kw(s, t):
            tags = []
            if s:
                tags.append("src")
            if t:
                tags.append("tgt")
            return "+".join(tags) if tags else "—"

        print(
            f"{r['filename']:<16}"
            f"{short_kw(r['visionvapt_clean_source'], r['visionvapt_clean_target']):<12}"
            f"{short_kw(r['visionvapt_adv_source'], r['visionvapt_adv_target']):<12}"
            f"{'YES' if r['visionvapt_desc_changed'] else 'NO':<9}"
            f"{'YES' if r['visionvapt_source_removed'] else 'NO':<7}"
            f"{'YES' if r['visionvapt_target_appeared'] else 'NO':<8}"
            f"{'YES' if r['visionvapt_full_transfer'] else 'NO':<9}"
        )

    # --- Aggregate ---
    vv_changed = sum(1 for r in results if r["visionvapt_desc_changed"])
    vv_src_rm = sum(1 for r in results if r["visionvapt_source_removed"])
    vv_tgt_app = sum(1 for r in results if r["visionvapt_target_appeared"])
    vv_full = sum(1 for r in results if r["visionvapt_full_transfer"])

    llava_tgt = sum(1 for r in results if r["llava_target_appeared"])
    llava_ch = sum(1 for r in results if r["llava_desc_changed"])

    avg_clean_time = sum(r["visionvapt_clean_time"] for r in results) / total
    avg_adv_time = sum(r["visionvapt_adv_time"] for r in results) / total

    print()
    print("=" * 70)
    print("AGGREGATE METRICS")
    print("=" * 70)

    print()
    print(f"  Images evaluated           : {total}")
    print(f"  Total time                 : {total_time:.1f}s")
    print()
    print(f"  White-box (LLaVA-1.5-7B):")
    print(f"    Description changed      : {llava_ch}/{total} ({llava_ch/total*100:.1f}%)")
    print(f"    Target keyword appeared  : {llava_tgt}/{total} ({llava_tgt/total*100:.1f}%)")
    print()
    print(f"  Black-box (vision-vapt API):")
    print(f"    Description changed      : {vv_changed}/{total} ({vv_changed/total*100:.1f}%)")
    print(f"    Source keyword removed   : {vv_src_rm}/{total} ({vv_src_rm/total*100:.1f}%)")
    print(f"    Target keyword appeared  : {vv_tgt_app}/{total} ({vv_tgt_app/total*100:.1f}%)")
    print(f"    Full transfer success    : {vv_full}/{total} ({vv_full/total*100:.1f}%)")
    print()
    print(f"  Timing:")
    print(f"    Avg clean query          : {avg_clean_time:.2f}s")
    print(f"    Avg adv query            : {avg_adv_time:.2f}s")
    print()
    print(f"  Perturbation budget:")
    print(f"    Epsilon                  : 8/255 = {8/255:.6f}")
    print(f"    All within budget        : {all(r['within_budget'] for r in results)}")

    # --- Descriptions comparison ---
    print()
    print("=" * 70)
    print("DESCRIPTIONS COMPARISON")
    print("=" * 70)

    for r in results:
        print()
        print(f"  {r['filename']}:")
        print(f"    LLaVA clean:    {r['llava_clean_desc'][:120]}")
        print(f"    LLaVA adv:      {r['llava_adv_desc'][:120]}")
        print(f"    vision-vapt clean: {r['visionvapt_clean_desc'][:120]}")
        print(f"    vision-vapt adv:   {r['visionvapt_adv_desc'][:120]}")

    # --- Save aggregate JSON ---
    aggregate = {
        "timestamp": datetime.now().isoformat(),
        "total_time": total_time,
        "configuration": {
            "white_box_model": "LLaVA-1.5-7B (bfloat16)",
            "black_box_model": MODEL_NAME,
            "api_base_url": BASE_URL,
            "epsilon": 8 / 255,
            "source_keyword": SOURCE_KEYWORD,
            "target_keyword": TARGET_KEYWORD,
            "question": QUESTION,
            "max_tokens": MAX_TOKENS,
            "adv_dir": ADV_DIR,
        },
        "images_evaluated": total,
        "white_box_metrics": {
            "description_changed": llava_ch,
            "description_changed_pct": llava_ch / total * 100,
            "target_appeared": llava_tgt,
            "target_appeared_pct": llava_tgt / total * 100,
        },
        "black_box_metrics": {
            "description_changed": vv_changed,
            "description_changed_pct": vv_changed / total * 100,
            "source_removed": vv_src_rm,
            "source_removed_pct": vv_src_rm / total * 100,
            "target_appeared": vv_tgt_app,
            "target_appeared_pct": vv_tgt_app / total * 100,
            "full_transfer": vv_full,
            "full_transfer_pct": vv_full / total * 100,
        },
        "timing": {
            "avg_clean_query": avg_clean_time,
            "avg_adv_query": avg_adv_time,
        },
        "per_image_results": results,
    }

    aggregate_path = os.path.join(output_dirs["results"], "aggregate_results.json")
    save_json(aggregate, aggregate_path)
    print()
    print(f"  Saved aggregate results: {aggregate_path}")

    # --- Save summary text report ---
    report_path = os.path.join(output_dirs["base"], "summary_report.txt")
    with open(report_path, "w") as f:
        f.write("=" * 70 + "\n")
        f.write("TRANSFER ATTACK SUMMARY: LLaVA-1.5-7B → vision-vapt\n")
        f.write("=" * 70 + "\n\n")
        f.write(f"Timestamp: {datetime.now().isoformat()}\n")
        f.write(f"Total time: {total_time:.1f}s\n")
        f.write(f"Images evaluated: {total}\n\n")

        f.write("Configuration:\n")
        f.write(f"  White-box: LLaVA-1.5-7B (bfloat16, 300 PGD iters)\n")
        f.write(f"  Black-box: {MODEL_NAME} ({BASE_URL})\n")
        f.write(f"  Epsilon: 8/255 = {8/255:.6f} (max 3.1% per pixel)\n")
        f.write(f"  Source keyword: {SOURCE_KEYWORD}\n")
        f.write(f"  Target keyword: {TARGET_KEYWORD}\n\n")

        f.write("White-box (LLaVA-1.5-7B) results:\n")
        f.write(f"  Description changed: {llava_ch}/{total} ({llava_ch/total*100:.1f}%)\n")
        f.write(f"  Target appeared: {llava_tgt}/{total} ({llava_tgt/total*100:.1f}%)\n\n")

        f.write("Black-box (vision-vapt) results:\n")
        f.write(f"  Description changed: {vv_changed}/{total} ({vv_changed/total*100:.1f}%)\n")
        f.write(f"  Source removed: {vv_src_rm}/{total} ({vv_src_rm/total*100:.1f}%)\n")
        f.write(f"  Target appeared: {vv_tgt_app}/{total} ({vv_tgt_app/total*100:.1f}%)\n")
        f.write(f"  Full transfer: {vv_full}/{total} ({vv_full/total*100:.1f}%)\n\n")

        f.write("Per-image descriptions:\n")
        for r in results:
            f.write(f"\n  {r['filename']}:\n")
            f.write(f"    LLaVA clean:      {r['llava_clean_desc'][:150]}\n")
            f.write(f"    LLaVA adv:        {r['llava_adv_desc'][:150]}\n")
            f.write(f"    vision-vapt clean: {r['visionvapt_clean_desc'][:150]}\n")
            f.write(f"    vision-vapt adv:   {r['visionvapt_adv_desc'][:150]}\n")

    print(f"  Saved summary report: {report_path}")

    print()
    print("=" * 70)
    print("Transfer evaluation complete.")
    print(f"  All outputs saved to: {output_dirs['base']}")
    print("=" * 70)


if __name__ == "__main__":
    main()
