    print()
    print("=" * 70)
    print("AGGREGATE METRICS")
    print("=" * 70)

    print()
    print(f"  Images evaluated           : {total}")
    print(f"  Total time                 : {total_time:.1f}s")
    print()
    print(f"  White-box (Qwen2-VL-2B):")
    print(f"    Description changed      : {qwen_ch}/{total} ({qwen_ch/total*100:.1f}%)")
    print(f"    Source keyword removed   : {qwen_src_rm}/{total} ({qwen_src_rm/total*100:.1f}%)")
    print(f"    Target keyword appeared  : {qwen_tgt}/{total} ({qwen_tgt/total*100:.1f}%)")
