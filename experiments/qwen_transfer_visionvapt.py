"""
Transfer Attack Evaluation: Qwen2-VL-2B (white-box) -> vision-vapt (black-box API)

Tests whether adversarial perturbations crafted on Qwen2-VL-2B (white-box)
transfer to the vision-vapt model served via the OAC API (black-box).

Hypothesis: Qwen2-VL-2B shares the same vision encoder family, connector
(PatchMerger), tokenizer, and LLM family as vision-vapt (Qwen MoE 100B+).
Same-family transfer should work better than cross-architecture (LLaVA -> Qwen).

Pipeline:
  1. Load adversarial images generated by Qwen2-VL-2B (epsilon=8/255, 300 iters)
  2. Load corresponding original images
  3. Query vision-vapt API with both clean and adversarial images
  4. Compare descriptions: did "cat" appear? did "dog" disappear?
  5. Compare with LLaVA -> vision-vapt transfer results (if available)

Output:
  outputs/qwen_transfer_visionvapt/
    results/              -- per-image JSON + aggregate JSON
    summary_report.txt    -- text summary

Usage:
    PYTHONPATH=. .venv/bin/python experiments/qwen_transfer_visionvapt.py
    PYTHONPATH=. .venv/bin/python experiments/qwen_transfer_visionvapt.py --image dog01.jpg
"""

